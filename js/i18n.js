function applyLanguage(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.cs;
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const key = el.getAttribute('data-i18n-alt');
    if (dict[key] !== undefined) el.setAttribute('alt', dict[key]);
  });

  const label = document.querySelector('[data-lang-label]');
  if (label) label.textContent = lang === 'cs' ? 'EN' : 'CS';

  try { localStorage.setItem('wedding_lang', lang); } catch (e) {}
}

function initLanguage() {
  let lang = 'cs';
  try { lang = localStorage.getItem('wedding_lang') || 'cs'; } catch (e) {}
  applyLanguage(lang);

  const toggle = document.getElementById('lang-toggle');
  if (toggle) {
    toggle.addEventListener('click', () => {
      const current = document.documentElement.lang === 'en' ? 'en' : 'cs';
      applyLanguage(current === 'cs' ? 'en' : 'cs');
    });
  }
}

document.addEventListener('DOMContentLoaded', initLanguage);
